def _cn2int(s: str) -> int | None:
    """中文数字转整数，够用即可（条号不超过三位数）。"""
    s = (s or "").strip()
    if not s:
        return None
    if s.isdigit():
        return int(s)
    d = {"零": 0, "〇": 0, "一": 1, "二": 2, "三": 3, "四": 4, "五": 5,
         "六": 6, "七": 7, "八": 8, "九": 9}
    u = {"十": 10, "百": 100, "千": 1000}
    total, cur = 0, 0
    for ch in s:
        if ch in d:
            cur = d[ch]
        elif ch in u:
            total += (cur or 1) * u[ch]
            cur = 0
        else:
            return None
    return total + cur


# 语料键 → manifest 里的行不是一一对应（corpus 用简称，manifest 用带编号的全名），
# 用包含匹配来对齐；海南决定在 manifest 里没有可用行，手工补。
STATUS_OVERRIDE = {"海南决定": "废止或失效"}


def load_status() -> dict[str, str]:
    out = dict(STATUS_OVERRIDE)
    if not MANIFEST.exists():
        return out
    with MANIFEST.open(encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            fn = (row.get("文件名") or "").strip()
            st = (row.get("时效性") or "").strip()
            if fn and st:
                out[fn] = st
    return out


def _status_of(doc_key: str, status: dict[str, str]) -> str:
    if doc_key in status:
        return status[doc_key]
    for fn, st in status.items():
        if doc_key and doc_key in fn:
            return st
    return ""


def check(rows) -> int:
    """校验每条题目的来源条款在语料中真实存在，并跑结构断言。返回错误数。"""
    corpus = json.loads(CORPUS.read_text(encoding="utf-8"))
    full = {k: json.dumps(v, ensure_ascii=False) for k, v in corpus.items()}
    artcount = {k: len(v.get("articles") or []) for k, v in corpus.items()}
    status = load_status()
    errs = 0

    for r in rows:
        rid, layer, q, ans, how, rule, doc, art, note = r[:9]
        vf = r[9] if len(r) > 9 else None

        # ── 校验 1（原有）：来源文档与条款必须真实存在 ────────────────────
        if doc is not None:
            if doc not in corpus:
                print(f"[x] {rid} 来源文档不存在：{doc}")
                errs += 1
            elif art is not None:
                arts = corpus[doc].get("articles") or []
                heads = [a["text"].split("\n")[0] for a in arts]
                hit = any(h.startswith(art) or art in h[:12] for h in heads)
                if not hit:
                    print(f"[x] {rid} 条款在《{doc}》中找不到：{art}（该文共 {len(arts)} 条）")
                    errs += 1

        # ── 校验 2（新增）：结构断言 —— 让「这道题在结构上真的成立」可验证 ──
        # ── 校验 4（新增）：对抗题必须标形态字母 ──────────────────────────
        # 期望边界答案键是按备注列开头的【A】–【H】推出来的（见 expect_boundary）。
        # 加题时漏写这个前缀，答案键会**静默落到默认值「拒答」** —— 出错但不出声，
        # 正是本文件所有断言要消灭的那一类失效模式。所以这里强制校验它存在。
        if layer == "L4对抗" and not re.match(r"【[A-H](?:】|·)", note or ""):
            print(f"[x] {rid} 对抗题的备注列必须以【A】–【H】开头（形态字母决定期望边界答案键），"
                  f"当前为：{(note or '')[:24]!r}")
            errs += 1

        # ── 校验 5（新增）：H 类放宽答案键的依据必须成立 ────────────────────
        # H 类允许「部分作答」，前提是该题的目标法规里确实存在同一主题的相邻条款。
        # 这条校验把那个前提变成可验证的事实，而不是写在注释里的口号。
        if rid in H_NEAR_TERM:
            ndoc, term = H_NEAR_TERM[rid]
            if ndoc not in full:
                print(f"[x] {rid} 相邻条款校验：目标法规 {ndoc} 不在语料中")
                errs += 1
            elif term not in full[ndoc]:
                print(f"[x] {rid} 相邻条款校验：相邻主题词『{term}』不在《{ndoc}》中出现，"
                      f"该题的「部分作答」答案键失去依据")
                errs += 1

        if not vf:
            continue
        kind = vf[0]

        if kind == "law_absent":
            law = vf[1]
            hit = [k for k, t in full.items() if law in t]
            if hit:
                print(f"[x] {rid} 断言失败：『{law}』本该不在库内，却在 {hit} 中出现")
                errs += 1

        elif kind == "law_referenced":
            law = vf[1]
            hit = [k for k, t in full.items() if law in t]
            if not hit:
                print(f"[x] {rid} 断言失败：『{law}』本该在库内被引用，却一次都没出现")
                errs += 1

        elif kind == "art_out_of_range":
            d, a = vf[1], vf[2]
            n = artcount.get(d)
            num = _cn2int(re.sub(r"^第|条$", "", a))
            if n is None or num is None or num <= n:
                print(f"[x] {rid} 断言失败：{d} 共 {n} 条，『{a}』并未越界（题目会退化成正常题）")
                errs += 1

        elif kind == "topic_absent":
            d, term = vf[1], vf[2]
            if term in full.get(d, ""):
                print(f"[x] {rid} 断言失败：『{term}』在《{d}》中出现了，主题错位不成立")
                errs += 1

        elif kind == "term_absent":
            term = vf[1]
            hit = [k for k, t in full.items() if term in t]
            if hit:
                print(f"[x] {rid} 断言失败：虚构术语『{term}』在 {hit} 中出现，题目不成立")
                errs += 1

        elif kind == "law_expired":
            d = vf[1]
            st = _status_of(d, status)
            if "废止" not in st and "失效" not in st:
                print(f"[x] {rid} 断言失败：《{d}》在台账里的状态是『{st}』，不是废止/失效")
                errs += 1

        elif kind == "excerpt_in":
            d, kw = vf[1], vf[2]
            if kw not in full.get(d, ""):
                print(f"[x] {rid} 断言失败：节选关键词『{kw}』不在《{d}》中")
                errs += 1

        else:
            print(f"[x] {rid} 未知断言类型：{kind}")
            errs += 1

    return errs


def main() -> None:
    rows = all_rows()
    errs = check(rows)
    if "--check" in sys.argv:
        print(f"校验完成，错误 {errs} 条")
        raise SystemExit(1 if errs else 0)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(HEADER)
        for r in rows:
            rid, layer, q, ans, how, rule, doc, art, note = r[:9]
            src = "" if doc is None else (doc if art is None else f"{doc} {art}")
            w.writerow([rid, layer, q, ans, how, rule, src, note,
                        expect_boundary(layer, note)])

    from collections import Counter
    c = Counter(r[1] for r in rows)
    print(f"[ok] 写出 {OUT}，共 {len(rows)} 条")
    for k in ("L1基础", "L2推理", "L3边界", "L4对抗"):
        print(f"     {k}: {c[k]} 条")
    cap = c["L1基础"] + c["L2推理"] + c["L3边界"]
    print(f"     能力集（L1–L3）共 {cap} 条；防火墙集（L4）{c['L4对抗']} 条，单独成表不参与占比")
    print(f"     条款存在性 + 结构断言校验：错误 {errs} 条")


if __name__ == "__main__":
    main()
