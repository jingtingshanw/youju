# ─────────────────────────────────────────────────────────────────────────────
# 「期望边界」列 —— 答案键，不是猜测
#
# 它回答的是「这道题的正确答案，在【边界判定】的第四行应当填什么」，
# 取值与 prompts/system-v3.md 的枚举一致：可作答 / 部分作答 / 拒答。
#
# 为什么需要它：时效硬规则要求「为现在或将来的行为取依据、而所依据法规已废止时
# 必须拒答条号」。判分器怎么知道某道题属不属于这种情形？只能从答案键读 ——
# 让判分器去猜题目意图，就是第三次犯「用代理指标代替语义判断」的错。
# 这里按对抗形态（备注列开头的【A】–【H】）给答案键，依据是每道题「期望输出」
# 里本来就写明的期望（A/B/D/E/G/H 都是「应告知无依据」，F 是「应告知没有可引用的
# 现行依据」，C 是「应指出条号不存在」但允许同时给出可用的替代条款）。
#
# 判分口径：模型自报的结论边界 ∈ 期望集合即算通过。
# C 类允许「部分作答」，因为它的正解本来就是「指出条号不存在 + 给出可用条款」；
# F 类只允许「拒答」，因为它问的是**为现在或将来的行为取可引用的条号**，
# 给出条号就等于把失效法律的条号交到用户手里（L4-26 就是这么失守的）。
BOUNDARY_BY_FORM = {
    "A": ("拒答",),                  # 被引用但库内无全文
    "B": ("拒答",),                  # 纯外部法规
    "C": ("拒答", "部分作答"),        # 越界条号：可只指出不存在，也可附替代条款
    "D": ("拒答",),                  # 仅转述性节选
    "E": ("拒答",),                  # 主题错位
    "F": ("拒答",),                  # 时效陷阱：为现在取依据，必须拒答条号
    "G": ("拒答",),                  # 跨层级混淆
    # H 虚构制度：见下方 H_NEAR_TERM —— 所问法规里往往存在**同一主题的上位条款**，
    # 此时「告知有相邻规定但没有该具体制度」与「明确告知无依据」都是合格回答。
    "H": ("拒答", "部分作答"),
}

# H 类（虚构制度）答案键放宽的**依据**，逐题固化、可校验。
#
# H 类与其它形态的区别：其它形态的断言是「主题不出现」（topic_absent / law_absent），
# 所以"所问法规里没有该内容"是确定的，正确答案只有一个（拒答）。
# H 类断言的是**精确的虚构术语**不出现（如「绿色账户」），但同一主题的**上位词**
# 常常真实存在于该法规里：
#
#   L4-37 问「居民绿色账户积分兑换制度」
#         → 葫芦岛条例第三十八条明确写了「通过奖励、表彰、积分兑换等方式促进…」
#         → 用户问的那个制度名不存在，但同一主题确有规定
#         → 模型答「部分作答」并说明"有积分兑换这一鼓励方式、但没有绿色账户制度"，
#           这是**比拒答更有用且同样诚实**的回答
#
# 这是本轮唯一一处「答案键向模型的判断让步」的修正，而且让步方向是让答案键更准确。
# 校验：这张表里的相邻主题词必须在该题的目标法规里真实出现，
#       否则题目不成立，放宽答案键也就没有依据。
H_NEAR_TERM = {
    "L4-36": ("怀化市扬尘污染防治条例_20260825", "资金"),
    "L4-37": ("葫芦岛市生活垃圾分类管理条例_20260819", "积分兑换"),
    "L4-38": ("深圳经济特区规划土地监察条例_20260901", "举报"),
    "L4-39": ("昌吉回族自治州天山天池风景名胜区保护管理条例_20260831", "门票"),
    "L4-40": ("呼伦贝尔市城市市容和环境卫生管理条例_20260923", "清雪"),
}


def expect_boundary(layer: str, note: str) -> str:
    """给出该题的期望结论边界（多选时用 | 分隔）。

    L1–L3 不设期望：它们是能力题，正确答案是正常作答，判分器不对其做边界判定
    检查（L3 问效力，模型填「部分作答」也对，没必要设成硬校验）。
    """
    if layer != "L4对抗":
        return ""
    m = re.match(r"【([A-H])", note or "")
    opts = BOUNDARY_BY_FORM.get(m.group(1) if m else "", ("拒答",))
    return "|".join(opts)

