"""生成 RAG 评估集（golden set）。

为什么用脚本生成而不是手写 CSV：
  1. 每条题目的「来源」都必须能在 `data/corpus.json` 里反查到真实条款，
     脚本生成时顺带做一致性校验（条款号存在性、正文关键词存在性），
     防止出题人拍脑袋写一条语料里根本没有的题 —— 那会把 L1 污染成 L4。
  2. 后续要扩题、调占比，改列表即可重跑，不会出现手改 CSV 改坏格式的情况。

分层设计（能力集 40 / 25 / 20，防火墙集单列）：
  L1 基础：单点事实检索，答案就在某一条里
  L2 推理：需要拼两处以上信息，或需要读懂表格结构
  L3 边界：时效 / 废止 / 引用与全文的区别 —— 这是本产品的核心价值区
  L4 对抗：语料里根本没有的东西，考察「敢不敢说不知道」

关于 L4 的样本量与占比（2026-10-14 扩容）：
  L4 从 4 道扩到 40 道，**不再遵守 15% 的占比**。原因：
    · L1–L3 是「能力集」——考的是答得对不对，占比要按业务分布设计；
    · L4 是「防火墙集」——它的用途是**标定 rerank 的拒答阈值**，
      需要的是把分数分布打实（每一类形态都要有足够样本），而不是保持某个比例。
  所以报告里 L4 单独成表，不和 L1–L3 混算总占比。这一点写进 `eval/README.md`。

  L4 的 8 类形态（每类 5 道），覆盖「不可能有依据」的不同成因：
    A 被引用但库内无全文   法规名真实出现在库内（制定依据里），但库中只有名字
    B 纯外部法规           法规名在库内一次都没出现（外地/上位法）
    C 越界条号             真法规 + 真主题 + 假条号（条号 > 该法规实际条数）
    D 转述性节选           库内有片段，但它是嵌在别处的「被调整对象」，不可独立引用
    E 主题错位             真法规 + 该法规根本不涉及的主题
    F 时效陷阱             问已废止/已失效法规的「现在怎么执行」
    G 跨层级混淆           问国家/省级层面规定，库内只有市/州级
    H 虚构制度             问题措辞合法，但库里根本没有这套制度/术语

**每道 L4 题都挂一条结构断言（第 10 个字段 verify）**，生成时由程序验证这道题
在结构上真的成立。这是本轮扩容最重要的质量保障：
  · D 类题若把条号写成库里存在的，题目就从「对抗题」变成「正常题」；
  · E 类题若该主题其实在那部法规里出现过，答案就不是「无依据」而是「有依据」；
  · H 类题若那个术语在库里出现过，就变成了一道普通检索题。
靠人肉检查这 40 条，一定会漏。断言让这个失效模式不可用。

用法：
    python scripts/build_eval_set.py            # 生成 eval/golden-set.csv
    python scripts/build_eval_set.py --check    # 只做全部校验（含结构断言）
"""
