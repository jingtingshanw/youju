#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""第三步：撰写结论与建议。

## 这里跟「回答问题」的区别

问「历史文化街区更新要注意什么」，资料里能翻出一堆条款，拼起来就是一篇
像样的回答。但规划师真正要交出去的东西不是这个——他要的是：

    这个项目按什么路径报、受哪几条硬约束、哪几条是自己得去争的、
    哪一块现在没依据所以先别动。

所以输出的是四段固定结构，不是一段流畅的散文：

    结论   一句话：这事能不能做、按什么名义做
    依据   分层的依据清单，每条必须能指到文件（能指到条号更好）
    缺口   哪些方向没找到依据。**这一段是这份报告最有用的部分**
    下一步 动作级建议：办什么事、找谁、拿哪条去说

「缺口」为什么最有价值：用户问「想知道相关的文件」，真实的处境是
他不知道有什么、也不知道缺什么。只给已有的，他仍然不知道边界在哪。
明确写「省级层面没有检索到专门的条例」，他才知道这一层要另想办法。

## 两种资料必须分开喂

有正文的文件（18,608 份国家级）可以引条号、引原话；
只有目录的文件（65,xxx 条地方条目）只有标题、文号、日期、链接。

混在一起喂，模型会对着一个标题编出内容——「《南京市城市更新办法》
第五条规定…」这种，看起来最专业，实际最危险。所以分两栏，
且在提示词里把「只能写什么」写死。
"""
from __future__ import annotations

from datetime import date

WRITE_SYS = """你是执业二十年的城乡规划师。现在有一个同行带着一个具体项目来找你，
他要拿这份东西去和领导、甲方、审批部门对话。他要的不是「有哪些相关文件」，
是**「这件事到底能不能办、卡在哪、有几条路、你建议我走哪条」**。

## 输入

两类资料，处理方式完全不同：

【A 有正文】可以引用具体条款和原话。
【B 仅目录】只有标题、文号、日期、链接，**没有任何正文**。

对 B 类，你只能写「据《XX》（文号，日期）」这类事实性陈述，
**绝对不能写出它的具体条文内容**——你没看到正文，写出来的每个字都是编的。

## 输出格式（五段，二级标题，顺序固定）

## 判断

**先给立场，再给理由。** 3—6 句。

第一句必须是可执行的判断，三选一：能做 / 不能做 / 有条件能做（条件是什么）。
不要写「需要根据具体情况判断」——那是把问题退回去。

接着说清三件事：
- 真正的堵点在哪一条（不是最全的那份文件，是最硬的那一条）
- 这个堵点是「明文禁止」还是「程序没走到」（两者处理方式完全不同）
- 如果资料里有互相冲突的规定，冲突在哪、按什么规则解（上位法优先 / 新法优先 / 特别规定优先）

**涉及施行日期、过渡期时，先跟输入里的「今天日期」比一下再写。**
新修订的条例常写「自 2026 年 7 月 1 日起施行」——如果今天已经过了这个日期，
它就是现行有效版本，不要再提醒用户「届时才生效」「需核对旧版过渡期」，
那是把已决的事说成未决，会让人白跑一趟。只有在施行日**还没到**时，才提过渡期。

## 依据

按**约束的性质**分三档，不按文件层级罗列。同一档内按效力从高到低：

**一、硬约束**——不许突破的。违反就是违法，不是「需要论证」。
**二、程序义务**——可以做，但必须走完的手续、必须拿到的批复。
**三、可争取的空间**——条文留了口子、允许论证或特批的地方。这一档最有价值，
因为它是方案的余地所在，要写清「口子开在哪、要什么条件才能用」。

每条的写法（**引文必须在引注前面，这是硬格式**）：

    一句话说清这条约束管什么，原文：「逐字照抄的那一句」【《文件全名》第X条】

**每条都要带引文。** 这一段存在的意义就是这个：用户要看的不是「有一条法规管这事」，
是「法规原文怎么说的」。

引号里必须逐字照抄：不许概括、不许合并三条成一条、不许改标点。
为什么这么严——系统会拿引号里每个字回原文比对一遍，对不上就标出来。
你概括过一遍，用户看到的是「引文对不上」，他会以为是系统错。

真遇到整条太长、摘一句会断章取义的（一连串列举、勾着三四个分项），
引号里就写「（条款过长，未摘）」。系统会标「未核」，不是「引文有误」，
这是诚实的做法，比硬凑一句强。

最坏的做法是「半抄半概括」：加了引号，内容却被自己压过一遍。那比不写引文糟得多。

B 类（仅目录）只能从标题、文号、发布机关、日期这些**确定的事实**写起：
- 据《文件全名》（文号，日期），该文件已由某某机关发布 → 【《文件全名》】
- 从文件名称看，该文件针对的是…（必须带「从名称看」这类限定词）
不要只写「据《XX》」四个字就结束，也不要给只有目录的文件编条号。

**但 B 类不是依据，是线索。** 这一段的每一条都在回答「哪条约束管着我」，
而只有标题的文件回答不了这个问题——它只能说明「世上存在这么一份文件」。
所以：

- **依据段只写 A 类。** 一份文件如果只有标题，就不要出现在依据段，
  哪怕它的标题看起来最切题。
- B 类写到「缺口」段去，写成「《某文件》本库只有目录、无正文，需调取原文核实」。
  这比塞进依据段有用得多：用户知道该去要哪份文件。
- 宁可依据段只有 5 条真条文，也不要 6 条真条文 + 3 条「从名称看它是关于这件事的」。
  后者一眼就能看出是凑数，会把前面真条文的分量一起拉低。

引注括号里只放《文件名》和条号，不要放文号、日期、说明：
  对：【《南京市城市更新办法》】  对：【《历史文化名城名镇名村保护条例》第二十二条】
条号用中文数字（第二十二条），不用 22。

一行里的顺序固定：**先说要管什么 → 再摘原文 → 最后标引注**。
引文和引注之间不要插别的引号内容，也不要把引文放到引注后面——
系统是按「引注左边最近的那个引号」来配对的，位置错了就配不上，白摘。

## 路径

**这一段决定这份东西有没有用。** 把可行的路子列出来，通常是 2—4 条。
每条一行，必须同时说清四件事：

1. **路径名**（走什么名义办）
2. **审批层级**（谁点头：区里 / 市局 / 市政府 / 省厅 / 部里）
3. **周期**（要多久，说数量级：一个月 / 半年 / 一年以上）
4. **主要代价或风险**（改方案多少、要补什么论证、要放弃什么）

排序按「代价从小到大」，不按「效果从好到坏」——规划师先看哪条能办成。

如果只有一条路，就写一条，别凑数。
如果一条都走不通，直接写「没有合规路径」，并说清是哪一条把它彻底堵死的。

## 缺口

列出这次没找到依据的方向。每条一行，说清「哪一层、缺什么、这意味着什么」。

两类都写进来：
- 整个方向没检索到（省级没有专门条例 / 片区控规没入库）
- 方向检索到了、但**只有标题没有正文**（B 类）——写成「《某文件》本库只有目录，
  需调取原文核实其具体要求」，不能说「该文件对此作了规定」

**这一段是整份报告最有用的部分**，因为用户真实的处境是他不知道边界在哪。
例：省级层面未检索到专门的历史文化名城保护条例，报省审查时需另行确认省口径。
如果某方向确实找到了，不要写进这一段。

## 下一步

3—6 条动作，每条必须具体到「办什么事、找谁、拿哪条去说」：

1. 动作 —— 依据【《文件全名》第X条】；对谁说：某某部门；要什么：某某批复

不要写「加强学习」「高度重视」「建议进一步研究」这类空话。
每条都要是明天就能开始做的事。

## 硬约束

1. 每个判断后面必须有【】引注，引注里的文件名必须来自我给的资料。
2. 引注里的条号必须真的存在于那份文件里；不确定就只写文件名、不写条号。
3. 引号里只放逐字原文。概括、压缩、改写过的句子一律不加引号。
4. 资料里没有的，写进「缺口」，不要用常识补。
5. 不写开场白、不写总结段落、不解释你在做什么。
6. 中文。不用「首先/其次/最后」堆段落，不用「综上所述」。"""


SHORT_BODY = 800


def split_sources(picked: list[dict], bodies: list[dict]) -> tuple[str, str, str]:
    """把资料切成三栏：有正文 / 只有目录 / 只有公布公告。

    第三栏是这轮新加的。南京的规划类文件（《南京市城市更新专项规划》
    《总统府历史文化街区保护规划》）源站只发一两百字的「批后公布」公告，
    规划本体是图件。这类文件在库里是「有正文」的，但正文是个壳——
    给模型看，它就会照着自己脑补的内容写，核验时全部对不上。

    分栏之后，模型知道这几份只能写「已由某机关于某日公布」，不能写内容。
    """
    body_by_key = {b["doc_key"]: b for b in bodies if b.get("has_body")}
    # 联网抓来的正文块不在 kb.db 里，挂在条目自身上。之前只在有 body_key
    # 时才取正文，联网条目会被当成「只有目录」——刚抓下来的两万字白扔，
    # 模型只能说「从文件名称看」。
    web_by_title = {it["title"]: it.get("_blocks") for it in picked
                    if it.get("_blocks")}
    a_parts, b_parts, c_parts = [], [], []
    for i, it in enumerate(picked, 1):
        b = body_by_key.get(it.get("body_key") or "")
        if not b and web_by_title.get(it["title"]):
            b = {"blocks": web_by_title[it["title"]],
                 "n_art": it.get("n_art") or 0}
        src = "｜联网现抓·未入库" if it.get("where") == "web" else ""
        # 源端自带的时效标记要直接告诉模型。广州政策库标了「失效（提前废止）」的
        # 文件，如果不说，模型会拿它当现行依据写进结论——这是最严重的一类错。
        eff = ""
        if it.get("eff_hint") == "repealed":
            eff = f"｜**源端标注：{it.get('eff_state') or '已失效'}，不得作为现行依据**"
        # 本库台账的判定也要说。台账和源端标记是两条独立的线：源端只标了 800 多份，
        # 台账管全部 30,687 份，而且能认出「有效期届满」这种源端根本不会标的情况。
        st = it.get("eff") or ""
        d = it.get("eff_date") or ""
        if st == "expired":
            eff += f"｜**本库台账：有效期至 {d}，已届满，不得作为现行依据**"
        elif st == "pending":
            eff += f"｜**本库台账：自 {d} 起施行，尚未生效，引用须注明施行日**"
        elif st == "repealed":
            eff += "｜**本库台账：已废止，不得作为现行依据**"
        elif st == "superseded":
            eff += "｜**本库台账：同名法规已有新版，这是旧版，应引新版**"
        elif st == "in_force":
            eff += f"｜本库台账：有效期至 {d}，未届满"
        head = (f"[{i}]《{it['title']}》"
                f"（{it.get('doc_no') or '无文号'}｜{it.get('published') or '无日期'}"
                f"｜{it.get('region') or ''}{it.get('level') or ''}{src}{eff}）")
        if b and b.get("blocks"):
            txt = "\n".join(
                (f"{blk['label']}：{blk['text']}" if blk.get("label") else blk["text"])
                for blk in b["blocks"])
            # 不分条的文件要当场告诉模型。《省政府办公厅印发关于支持城市更新
            # 行动若干政策措施的通知》用「一、（一）」编号，模型却写
            # 「第十二条」，核验时条号不存在，6 处引注一起判失败，
            # 整份报告从「部分可核」掉到「需修正」——不是内容错，是编号体系不同。
            if b.get("n_art"):
                tag = ""
            else:
                tag = "〔全文按「一、（一）」编号，没有条款号——引这份只能写文件名〕"
            head = head[:-1] + tag + "）" if tag else head
            if len(txt) >= SHORT_BODY:
                a_parts.append(head + "\n" + txt)
            else:
                c_parts.append(f"{head}\n〔正文仅 {len(txt)} 字，是源站公告，无文件本体〕\n{txt}")
        else:
            b_parts.append(head + f"\n链接：{it.get('url') or '—'}")
    return "\n\n".join(a_parts), "\n".join(b_parts), "\n".join(c_parts)


def build_prompt(question: str, plan: dict, picked: list[dict],
                 bodies: list[dict]) -> tuple[str, str]:
    a, b, c = split_sources(picked, bodies)
    parts = [f"项目需求：{question}",
             f"检索范围：{plan.get('place', {}).get('city', '')}"
             f"{plan.get('place', {}).get('site', '')}".strip(),
             f"今天日期：{date.today().isoformat()}",
             ""]
    if a:
        parts.append(f"【A 有正文】共 {sum(1 for x in bodies if x.get('has_body'))} 份\n{a}")
    if b:
        n_b = sum(1 for x in picked if not x.get("body_key")
                  and not x.get("_blocks"))
        parts.append(f"【B 仅目录】共 {n_b} 份，无正文，只能引标题与文号\n{b}")
    if c:
        parts.append("【C 仅有公布公告】下面这几份，源站只发了几百字的公布公告，"
                     "规划/文件本体是图件，没进库。\n"
                     "只能写「该文件已由某机关于某日公布，批准文号是…」；"
                     "**不许**引用或概括它的内容要求——你看不到内容。\n"
                     "它们能证明「这份规划存在、已批复」，进不了依据段；"
                     "要引用具体要求，写进缺口段「需调取规划文本」。\n" + c)
    parts.append("\n请按五段结构输出：判断 → 依据 → 路径 → 缺口 → 下一步。"
                 "「判断」第一句必须给出能做/不能做/有条件能做的立场，"
                 "不要用「需视情况而定」收尾。"
                 "依据段只写 A 类——B、C 两类没有可引的条文，写到缺口段去。")
    return WRITE_SYS, "\n\n".join(parts)


# ══════════════════════════════════════════════════════════════════
# 降级路径：不调模型，直接排原文
# ══════════════════════════════════════════════════════════════════
#
# 这条路径不是为了省 token，是为了「模型挂了系统还在」。真实会遇到的三种情况：
#
#   1. 三家模型的 key 同时失效 / 集体限流（429）。撰写要 16 秒、烧 3,200 token，
#      是最容易被限流打中的一步，也是唯一一步失败后整份报告没了。
#   2. 内网或弱网环境调不通外网模型。剪掉内网这条线之后这条用不上了，但留着。
#   3. 有人只想看条文，不想要 AI 的概括——尤其律师和评审专家，
#      他们信原文，不信任何转述。
#
# 输出必须还是五段，否则前端 renderMD 会把整篇当成一段正文。
# 判断段和路径段如实写"没做"，不硬编一个像是分析的东西——
# 降级报告的价值恰恰在于它一眼看得出是降级，不会被误当成正常产出。
def raw_report(question: str, plan: dict, picked: list[dict],
               bodies: list[dict], reason: str = "") -> str:
    body_by_key = {b["doc_key"]: b for b in bodies if b.get("has_body")}
    eff_note = {"expired": "已届满，不得作为现行依据",
                "repealed": "已废止，不得作为现行依据",
                "superseded": "已有新版，本份为旧版",
                "pending": "尚未生效"}
    a_parts, b_parts, c_parts = [], [], []
    for it in picked:
        b = body_by_key.get(it.get("body_key") or "")
        blocks = (b or {}).get("blocks") or it.get("_blocks") or []
        title = it.get("title") or ""
        meta = "｜".join(x for x in (it.get("doc_no") or "",
                                     it.get("published") or "",
                                     it.get("region") or "") if x)
        note = eff_note.get(it.get("eff") or "", "")
        tail = f"（{meta}）" + (f"　**{note}**" if note else "")
        if not blocks:
            b_parts.append(f"- 《{title}》{tail}")
            continue
        art = [(blk.get("label") or "", (blk.get("text") or "").strip())
               for blk in blocks if (blk.get("text") or "").strip()]
        if not art:
            b_parts.append(f"- 《{title}》{tail}")
            continue
        # 每份最多 8 条、每条最多 220 字。降级报告是给人扫的，不是给模型读的，
        # 排到 30 条没人看；超过的量交给原文链接。
        keep = art[:8]
        lines = [f"{lab}：{txt[:220]}" if lab else txt[:220] for lab, txt in keep]
        more = f"\n  …另有 {len(art) - len(keep)} 条，见原文" if len(art) > len(keep) else ""
        a_parts.append(f"**《{title}》**{tail}\n" + "\n".join(
            f"- 《{title}》{lab}　{txt[:220]}" if lab else f"- 《{title}》　{txt[:220]}"
            for lab, txt in keep) + more)

    n_body = len(a_parts)
    out = [
        "## 判断",
        f"这一份是**原文条文清单**，不是分析结论。系统在{reason or '模型不可用'}"
        f"的情况下跳过撰写，直接按文件把条文排出来。",
        f"能引的有 {n_body} 份，逐条抄自原文，条号、文件名、文号都可以核；"
        "「能不能做」「该走什么路径」这两件事没有做，需要人来判。",
        "",
        "## 依据",
        "\n\n".join(a_parts) if a_parts else "（选中文件里没有一份带条文正文）",
        "",
        "## 路径",
        "本段在降级模式下不产出。路径判断依赖跨文件的程序衔接（哪一步报谁批、"
        "前置文件是哪些），这需要对条文做归纳，跳过模型就做不了。",
        "",
        "## 缺口",
    ]
    if b_parts:
        out.append(f"下面 {len(b_parts)} 份只有目录，没有正文，只能证明文件存在，"
                   "内容无从引用：")
        out.extend(b_parts)
    else:
        out.append("选中的文件全部有正文，没有「只有目录」的情况。")
